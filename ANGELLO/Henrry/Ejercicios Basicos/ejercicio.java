public class ejercicio {

    public static void main(String[] args) {

        String k = "19";

        System.out.println("Mi edad es " + k + " años");
    }
    // Java, Dart y Visual Basic tienen una sintaxis diferente para realizar las
    // mismas tareas.
    // La diferencia principal es la forma de escribir el código, aunque los tres
    // pueden realizar la misma tarea.
    // Java es más estricto y requiere una estructura como public static void main,
    // Dart tiene una sintaxis más sencilla y utiliza void main(), mientras que
    // Visual Basic usa una sintaxis más cercana al
    // lenguaje natural, por ejemplo Dim para declarar variables y Console.WriteLine
    // para mostrar información.
}
